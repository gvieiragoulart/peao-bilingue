"""Builds src/peao_bilingue/ui/source_logos.py from each source's own icon.

The app has no Pillow (Tk reads PNG by itself but can't resize it well), so the logos
are resized here, once, into every size the window draws them at, and kept in the
module as PNG in base64: no data file for the .exe to carry.

    uv run --with pillow python packaging/source_icons.py <folder>

`<folder>` holds `<source>.png` or `<source>.ico`, the largest icon each site
publishes (its apple-touch-icon, manifest or favicon). Every logo becomes a rounded
tile; one with a transparent ground gets a white one, so a dark mark (GitHub's) still
shows in the dark theme. Hacker News publishes only an SVG, which Pillow can't read:
its "Y" is drawn here from that SVG's own path.

Remote OK is left out on purpose: its terms (the first item of its API's response)
ask not to use its logo. Sources without a logo get a drawn monogram in the app.
"""

import base64
import io
import sys
from pathlib import Path

from PIL import Image, ImageDraw

OUTPUT = (
    Path(__file__).parent.parent / "src" / "peao_bilingue" / "ui" / "source_logos.py"
)
# The sizes drawn, in pixels: the app's 20-40 px slots at 100-200 % scaling (the app
# takes the nearest one).
SIZES = (16, 20, 24, 28, 32, 40, 48, 56, 64, 80)
RADIUS = 0.22  # of the side: the tile's corners
SUPERSAMPLE = 4

# news.ycombinator.com/y18.svg (viewBox 4 4 188 188): an orange square and a white Y.
HN_ORANGE = (255, 102, 0, 255)
HN_Y = [
    (73.25, 45.01), (96.0, 92.40), (118.75, 45.01), (138.31, 45.01), (103.99, 109.50),
    (103.99, 150.99), (88.01, 150.99), (88.01, 109.50), (53.69, 45.01),
]  # fmt: skip


def load(path: Path) -> Image.Image:
    image = Image.open(path)
    if path.suffix == ".ico":
        image.size = max(image.info["sizes"])
    return image.convert("RGBA")


def hacker_news(side: int) -> Image.Image:
    image = Image.new("RGBA", (side, side), HN_ORANGE)
    scale = side / 188
    points = [((x - 4) * scale, (y - 4) * scale) for x, y in HN_Y]
    ImageDraw.Draw(image).polygon(points, fill=(255, 255, 255, 255))
    return image


def tile(logo: Image.Image, size: int) -> Image.Image:
    """The logo on a rounded tile of `size` pixels, drawn bigger and scaled down so the
    corners come out smooth."""
    side = size * SUPERSAMPLE
    ground = Image.new("RGBA", (side, side), (255, 255, 255, 255))
    ground.alpha_composite(logo.resize((side, side), Image.LANCZOS))
    mask = Image.new("L", (side, side), 0)
    ImageDraw.Draw(mask).rounded_rectangle(
        (0, 0, side - 1, side - 1), radius=round(side * RADIUS), fill=255
    )
    ground.putalpha(mask)
    return ground.resize((size, size), Image.LANCZOS)


def encoded(image: Image.Image) -> str:
    buffer = io.BytesIO()
    # A palette of 256 colors (alpha included) takes about half the room, and looks
    # the same at these sizes.
    image.quantize(256, method=Image.Quantize.FASTOCTREE).save(
        buffer, format="PNG", optimize=True
    )
    return base64.b64encode(buffer.getvalue()).decode("ascii")


def main(folder: Path) -> None:
    logos = {path.stem: load(path) for path in sorted(folder.iterdir())}
    logos["hackernews"] = hacker_news(SIZES[-1] * SUPERSAMPLE)
    logos.pop("remoteok", None)  # its terms: don't use the logo
    lines = [
        '"""The sources\' logos: PNG in base64, by size in pixels.',
        "",
        "Generated by packaging/source_icons.py from each site's own icon; don't edit by",
        'hand. A source missing here gets a drawn monogram (ui/source_icons.py)."""',
        "",
        "LOGOS: dict[str, dict[int, str]] = {",
    ]
    for name, logo in sorted(logos.items()):
        lines.append(f'    "{name}": {{')
        for size in SIZES:
            lines.append(f'        {size}: "{encoded(tile(logo, size))}",')
        lines.append("    },")
    lines.append("}")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUTPUT}: {len(logos)} logos, {OUTPUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
